#!/usr/bin/env bash
# SessionStart hook for Claude Code cloud sessions (claude.ai/code).
# No-op on a local machine. In the cloud VM it:
#   1. writes .env from the environment's variables (the clone has no .env,
#      and the dev server and local scripts expect one),
#   2. installs dependencies if the setup-script snapshot doesn't have them,
#   3. generates React Router route types (needed in a fresh checkout).
# Never put secret values in this file — they come from the cloud environment.
# See docs/cloud-environment.md.
set -euo pipefail

[ "${CLAUDE_CODE_REMOTE:-}" = "true" ] || exit 0

cd "${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel)}"

# Keys copied into .env when set in the cloud environment. Keep in step with
# the table in docs/cloud-environment.md.
KEYS=(
  SESSION_SECRET
  PUBLIC_STORE_DOMAIN
  PUBLIC_STOREFRONT_API_TOKEN
  PUBLIC_STOREFRONT_ID
  PUBLIC_CHECKOUT_DOMAIN
  PUBLIC_CUSTOMER_ACCOUNT_API_CLIENT_ID
  PUBLIC_CUSTOMER_ACCOUNT_API_URL
  SHOP_ID
  CUSTOM_COLLECTION_BANNER_METAFIELD
  OPS_ADMIN_API_TOKEN
  OPS_DASHBOARD_PASSWORD
)

HEADER="# Generated by scripts/cloud-session-start.sh from cloud environment variables."
# Write when absent, or refresh a .env this script generated earlier (resumed VM).
if [ ! -f .env ] || [ "$(head -n1 .env)" = "$HEADER" ]; then
  umask 077
  {
    echo "$HEADER"
    for k in "${KEYS[@]}"; do
      if [ -n "${!k:-}" ]; then
        printf '%s=%s\n' "$k" "${!k}"
      fi
    done
  } > .env
  echo "cloud-session-start: wrote .env ($(($(wc -l < .env) - 1)) keys)"
fi

if [ ! -d node_modules ]; then
  npm ci --no-audit --no-fund > /tmp/cloud-npm-ci.log 2>&1 \
    || echo "cloud-session-start: npm ci failed, see /tmp/cloud-npm-ci.log"
fi

npx react-router typegen >/dev/null 2>&1 || echo "cloud-session-start: react-router typegen failed (non-fatal)"
