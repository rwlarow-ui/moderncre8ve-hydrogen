#!/usr/bin/env node
/**
 * Writes app/data/held-products.js: the catalog-rollout handles on hold, each
 * with a display name and the collection a visitor should browse instead.
 *
 * The product route shows a "being refreshed" 404 for these handles. The
 * register itself (owners, blockers, approvals) must not ship to the client,
 * so only handle → name/collection is generated. Re-run after the register or
 * its current snapshot changes:
 *
 *   node scripts/build-held-products.mjs          # write the module
 *   node scripts/build-held-products.mjs --check  # exit 1 if it is stale
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const DIR = new URL("docs/catalog-rollout-2026-11/", ROOT);
export const OUTPUT = fileURLToPath(new URL("app/data/held-products.js", ROOT));

/**
 * Most specific first. Labels are curated because several Shopify collection
 * titles are SEO strings or all caps. Every handle here was checked live (200).
 */
export const COLLECTION_PRIORITY = [
  ["modern-bed-frames", "Modern Bed Frames"],
  ["mid-century-modern-credenza", "Media Consoles & Credenzas"],
  ["modern-dining-chairs", "Modern Dining Chairs"],
  ["benches", "Benches"],
  ["mid-century-modern-coffee-tables", "Coffee Tables"],
  ["nightstand-end-tables", "Nightstands & End Tables"],
  ["oval-dining-tables", "Oval Dining Tables"],
  ["custom-made-expandable-dining-tables", "Expandable Dining Tables"],
  ["mid-century-modern-dining-tables", "Mid-Century Modern Dining Tables"],
  ["bedroom", "Bedroom"],
  ["living", "Living Room"],
  ["dining", "Dining"],
];
export const FALLBACK_COLLECTION = {
  handle: "all-products",
  title: "All Furniture",
};

const readJson = (name) => JSON.parse(readFileSync(new URL(name, DIR), "utf8"));

/** "Warwick Solid Wood Bed Frame - Modern Platform…" → "Warwick Solid Wood Bed Frame". */
export function displayName(title) {
  return String(title).split(" - ")[0].trim();
}

export function pickCollection(collectionHandles) {
  const owned = new Set(collectionHandles);
  const match = COLLECTION_PRIORITY.find(([handle]) => owned.has(handle));
  return match ? { handle: match[0], title: match[1] } : FALLBACK_COLLECTION;
}

/** handle → { name, collection } for every held register entry, sorted by handle. */
export function buildHeldProducts(register, snapshot) {
  const collectionsByHandle = new Map(
    snapshot.products.map((p) => [
      p.handle,
      p.collections.nodes.map((c) => c.handle),
    ]),
  );
  const held = register.entries
    .filter((entry) => entry.disposition === "held")
    .map((entry) => [
      entry.handle,
      {
        name: displayName(entry.title),
        collection: pickCollection(collectionsByHandle.get(entry.handle) ?? []),
      },
    ])
    .sort(([a], [b]) => a.localeCompare(b));
  return Object.fromEntries(held);
}

export function renderModule(held) {
  return `// Generated by scripts/build-held-products.mjs from
// docs/catalog-rollout-2026-11/register.json. Do not edit by hand.

/** @typedef {{ name: string, collection: { handle: string, title: string } }} HeldProduct */

/** @type {Readonly<Record<string, HeldProduct>>} */
export const HELD_PRODUCTS = ${JSON.stringify(held, null, 2)};

/** @param {string | undefined | null} handle @returns {HeldProduct | null} */
export function getHeldProduct(handle) {
  return (
    (handle && Object.hasOwn(HELD_PRODUCTS, handle) && HELD_PRODUCTS[handle]) ||
    null
  );
}
`;
}

/** Format with the repo's Biome config so the output matches `biome:fix`. */
function biomeFormat(source) {
  return execFileSync("npx", ["biome", "format", "--stdin-file-path", OUTPUT], {
    cwd: fileURLToPath(ROOT),
    input: source,
    encoding: "utf8",
  });
}

export function generate({ format = true } = {}) {
  const register = readJson("register.json");
  const snapshot = readJson(register.currentSnapshot);
  const source = renderModule(buildHeldProducts(register, snapshot));
  return format ? biomeFormat(source) : source;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = generate();
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUTPUT, "utf8");
    if (current !== source) {
      console.error(
        "app/data/held-products.js is stale: run node scripts/build-held-products.mjs",
      );
      process.exit(1);
    }
    console.log("app/data/held-products.js is up to date.");
  } else {
    writeFileSync(OUTPUT, source);
    console.log(`Wrote ${OUTPUT}`);
  }
}
